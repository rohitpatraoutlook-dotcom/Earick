"""
Thought-experiment manual for Earick.

100 behavioral prompts for constructing and reasoning through
gedankenexperiments the way a physicist does.
"""

THOUGHT_EXPERIMENT_MANUAL = """
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
1.  WHAT A THOUGHT EXPERIMENT IS
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
1.  A thought experiment is not a daydream. It has a purpose:
    to expose a contradiction, clarify a definition, or reveal
    a consequence that pure algebra hides.
2.  Every thought experiment starts from a setup the reader can
    visualize in under 30 seconds. If it takes longer, simplify.
3.  The setup must be physically possible in principle, even if
    impractical. "Imagine a massless rope" is fine; "imagine
    gravity reversed" is not.
4.  The scenario must be constructed so that one assumption at
    a time can be tested. Vary one thing; hold everything else
    fixed.
5.  A good thought experiment has a clean answer. If the result
    is "it depends", the setup was too vague — refine it.
6.  The purpose is to make an abstract principle concrete.
7.  Thought experiments often involve idealizations:
    frictionless surfaces, point masses, perfect clocks.
    Name each idealization explicitly.
8.  A thought experiment is not a substitute for a real
    experiment. It is a tool for clarifying what a theory says.
9.  The best thought experiments end with a conclusion that
    feels inevitable in retrospect.
10. Use thought experiments when a formal derivation would be
    opaque, or when the assumptions of a theory need to be
    tested at their limits.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
2.  SETTING THE STAGE
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
11. State the observer's frame of reference before anything
    else. Every relativistic paradox is a frame confusion.
12. Specify the initial conditions fully: positions, velocities,
    fields, boundary conditions.
13. Name the physical laws that govern the scenario.
14. Choose the simplest possible geometry.
15. Choose the largest possible scale where the effect is
    visible, then scale down mentally.
16. Imagine yourself inside the scenario. What would you
    actually see, hear, or measure?
17. Draw the setup mentally. If you can't, the setup is too
    abstract to be useful.
18. Specify what is being measured and by whom.
19. Specify what is held constant during the experiment.
20. If the experiment involves a limit (v to c, T to 0, N to
    infinity), state which quantity is being pushed to the
    limit and which others are held fixed.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
3.  REASONING THROUGH THE SETUP
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
21. Follow the logic one step at a time. State each step in
    a sentence the reader can verify.
22. Do not skip to the conclusion. The path is the point.
23. At each step, ask: does this contradict any established
    law? If yes, either the setup or the law is being
    misapplied.
24. Track conserved quantities through every step: energy,
    momentum, angular momentum, charge, information.
25. If a quantity changes, explain where it came from or went.
26. Use limiting cases as checkpoints.
27. If two observers disagree, describe what each sees in
    their own frame. Both descriptions should be consistent.
28. Follow the scenario to its natural end. Don't stop at the
    first interesting moment.
29. If a step feels counterintuitive, slow down. The
    counterintuition is often the insight.
30. When the logic forces an uncomfortable conclusion, resist
    the temptation to add extra assumptions to avoid it.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
4.  CATEGORIES OF THOUGHT EXPERIMENTS
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
31. CONTRADICTION experiments: assume theory X is right, derive
    a result that violates Y (which is also established).
    Conclude X must be modified.
32. LIMIT experiments: take a known law and push a parameter to
    an extreme. See what breaks.
33. SYMMETRY experiments: imagine a scenario that should be
    invariant under a transformation, then check if the theory
    respects the invariance.
34. OBSERVER experiments: place two observers in relative
    motion and compare their measurements.
35. INFORMATION experiments: ask what information is available
    to an observer at a given point in spacetime.
36. MEASUREMENT experiments: imagine an idealized measurement
    apparatus and ask what it would read.
37. ENERGY-BOOKKEEPING experiments: follow every joule through
    a process. Any missing joule indicates a missing concept.
38. SCALE experiments: ask what happens at the smallest and
    largest scales a theory claims to cover.
39. EQUIVALENCE experiments: substitute one scenario for
    another that should be indistinguishable and see if the
    conclusion changes.
40. COSMOLOGICAL experiments: imagine a universe with one
    parameter changed and ask what would be different.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
5.  THE GREAT THOUGHT EXPERIMENTS (reference set)
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
41. Galileo's inclined planes and falling bodies: if heavy
    objects fell faster, a tied pair (light + heavy) would
    have to fall both faster and slower. Contradiction.
42. Newton's bucket: rotating water in a bucket curves its
    surface even when the water is at rest with the bucket.
    What is it rotating relative to?
43. Maxwell's demon: a small being sorts fast and slow
    molecules, seemingly violating the second law. Resolution:
    the demon needs information, which costs entropy.
44. Einstein's elevator: an accelerating elevator in deep space
    is locally indistinguishable from a gravitational field.
    Foundation of general relativity.
45. Einstein's light beam: what would you see if you rode
    alongside a light beam? Answer: light is always c.
    Foundation of special relativity.
46. Einstein-Podolsky-Rosen (EPR): two entangled particles
    measured far apart seem to communicate instantly.
    Foundation of Bell's theorem and quantum nonlocality.
47. Schrodinger's cat: a superposition amplified to a
    macroscopic scale.
48. Wigner's friend: an observer is observed. Reopens the
    measurement problem.
49. Twin paradox: one twin accelerates and returns younger.
50. Wheeler's delayed choice: a photon's behavior in an
    interferometer seems to depend on a choice made after it
    has passed.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
6.  COMMON FALLACIES
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
51. Mixing frames: computing a quantity in one frame and
    interpreting it in another.
52. Assuming simultaneity is absolute.
53. Treating mass as conserved when it can convert to energy.
54. Ignoring the cost of measurement.
55. Assuming instantaneous information transfer.
56. Confusing proper time with coordinate time.
57. Using Newtonian gravity outside its validity.
58. Assuming quantum superpositions must be macroscopic.
59. Assuming the observer has a privileged role.
60. Assuming "the universe" has a well-defined total energy.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
7.  CONSTRUCTING NEW THOUGHT EXPERIMENTS
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
61. Start with a tension. Find a place where two established
    principles seem to conflict.
62. Make the tension as sharp as possible by idealizing away
    everything that could explain it.
63. Simplify until the core conflict is unavoidable.
64. Run the scenario and see which principle gives way.
65. If neither gives way, look for a hidden assumption that
    made the conflict appear.
66. Generalize the resolution to the broader theory.
67. Try to construct a variant where the resolution fails.
68. If it succeeds, the resolution is not general enough.
69. State the experiment in one paragraph.
70. Name the experiment. Named experiments survive.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
8.  LIMITS AND EXTREME CASES
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
71. v to 0: the non-relativistic limit.
72. v to c: the ultra-relativistic limit.
73. hbar to 0: the classical limit.
74. N to infinity: thermodynamic limit.
75. T to 0: low-temperature limit.
76. r to 0: short-distance limit.
77. r to infinity: asymptotic behavior.
78. m to 0: massless limit.
79. E to infinity: high-energy limit.
80. Planck scale: the limit where both quantum and gravitational
    effects matter.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
9.  USING THOUGHT EXPERIMENTS IN ANSWERS
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
81. Use a thought experiment when a formula alone would be
    opaque. It gives intuition.
82. Use a thought experiment when the user's question is about
    "why" rather than "what".
83. Introduce the experiment in one sentence before using it.
84. Give the setup, not the whole derivation, when the answer
    needs to stay short.
85. Use the experiment to introduce a concept, then follow
    with the formula. Intuition first, formalism second.
86. If the user seems advanced, use a compact version of a
    classic experiment rather than inventing one.
87. If the user seems a beginner, use a vivid everyday analogy
    as the setting.
88. After the experiment, always state the takeaway.
89. Name real physicists' experiments when they exist.
90. If you construct an original experiment, mark it as such.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
10. FAILURE MODES
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
91.  Do not present a thought experiment as an actual
     experiment.
92.  Do not claim a thought experiment "proves" a theory.
93.  Do not construct a scenario so unrealistic that no
     physical theory could apply.
94.  Do not resolve a paradox by adding assumptions the theory
     does not allow.
95.  Do not confuse paradoxes of intuition with paradoxes of
     logic.
96.  Do not ignore the observer's role in relativistic setups.
97.  Do not extend a classical thought experiment into the
     quantum regime without checking it still makes sense.
98.  Do not treat textbook thought experiments as settled.
99.  Do not use thought experiments to bypass calculation.
100. Do not mistake a beautiful thought experiment for a true
     one. Beauty is a heuristic, not a proof.
"""


def get_thought_experiment_manual() -> str:
    """Return the full thought-experiment manual."""
    return THOUGHT_EXPERIMENT_MANUAL


def get_thought_experiment_subset(groups: list) -> str:
    """
    Return only selected blocks.

    Valid names: what_it_is, setting, reasoning, categories,
    great_experiments, fallacies, constructing, limits, using,
    failure_modes.
    """
    name_map = {
        "1.  WHAT":         "what_it_is",
        "2.  SETTING":      "setting",
        "3.  REASONING":    "reasoning",
        "4.  CATEGORIES":   "categories",
        "5.  THE GREAT":    "great_experiments",
        "6.  COMMON":       "fallacies",
        "7.  CONSTRUCTING": "constructing",
        "8.  LIMITS":       "limits",
        "9.  USING":        "using",
        "10. FAILURE":      "failure_modes",
    }

    wanted = {g.lower().replace(" ", "_") for g in groups}

    lines = THOUGHT_EXPERIMENT_MANUAL.split("\n")
    sections = {}
    current = None
    for line in lines:
        stripped = line.strip()
        matched = None
        for prefix, name in name_map.items():
            if stripped.startswith(prefix):
                matched = name
                break
        if matched:
            current = matched
            sections[current] = [line]
        elif current:
            sections[current].append(line)

    parts = []
    for g in groups:
        key = g.lower().replace(" ", "_")
        if key in sections:
            parts.append("\n".join(sections[key]))
    return "\n".join(parts)
